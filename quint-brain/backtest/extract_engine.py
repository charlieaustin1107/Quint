"""Pull the backtest engine out of Quint Brain so it can run outside the browser.

The strategy rules live inside quint-brain/index.html. Rather than rewrite them
(and risk the backtest testing something slightly different from what the app
teaches), this copies the exact functions, plus everything they depend on, into
quint-brain/backtest/engine.js.

Run it again whenever the rules in Quint Brain change:
    python3 quint-brain/backtest/extract_engine.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "quint-brain" / "index.html"
OUT = Path(__file__).resolve().parent / "engine.js"

# The entry points the backtests call.
WANT = ["blEval", "blStats", "orbEval", "pxSeries", "pxPois", "pxBacktest", "pbEval", "regime", "dkAgg", "dkClock", "fdSessKey", "etNow"]
# Browser-only things the engine never needs.
SKIP = {"document", "window", "localStorage", "fetch", "ST", "BS", "G"}

html = SRC.read_text(encoding="utf-8")
js = max(re.findall(r"<script[^>]*>(.*?)</script>", html, re.S), key=len)
lines = js.split("\n")

# Split the script into top-level blocks, each keyed by the name it declares.
head = re.compile(r"(?:async )?function (\w+)\s*\(|(?:const|let|var) (\w+)\s*=|class (\w+)")
starts = []
for i, line in enumerate(lines):
    m = head.match(line)
    if m:
        starts.append((i, m.group(1) or m.group(2) or m.group(3)))
blocks = {}
for k, (i, name) in enumerate(starts):
    j = starts[k + 1][0] if k + 1 < len(starts) else len(lines)
    body = "\n".join(lines[i:j]).rstrip()
    # drop a trailing section comment that belongs to the next block
    body = re.sub(r"\n/\*[^\n]*\*/\s*$", "", body)
    blocks.setdefault(name, body)

# Follow dependencies: any known top-level name used inside a block we keep.
keep, todo = [], list(WANT)
while todo:
    n = todo.pop()
    if n in keep or n in SKIP or n not in blocks:
        continue
    keep.append(n)
    for ident in set(re.findall(r"\b[A-Za-z_]\w*\b", blocks[n])):
        if ident in blocks and ident not in keep and ident != n:
            todo.append(ident)

order = [name for _, name in starts if name in keep]
seen = set()
parts = []
for name in order:
    if name in seen:
        continue
    seen.add(name)
    parts.append(blocks[name])

out = (
    "// AUTO-GENERATED by backtest/extract_engine.py from quint-brain/index.html. Do not edit by hand.\n"
    "// These are Quint Brain's own strategy and backtest functions, copied verbatim.\n"
    "/* eslint-disable */\n"
    + "\n".join(parts)
    + "\n\nmodule.exports = { " + ", ".join(n for n in WANT if n in seen) + ", BL };\n"
)
OUT.write_text(out, encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}: {len(seen)} blocks: {' '.join(order)}", file=sys.stderr)
