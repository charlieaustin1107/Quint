#!/usr/bin/env python3
"""Regenerate .github/ISSUE_TEMPLATE/recommend-resource.yml from config.yaml.

The category dropdown lists top-level categories only; sub-categories are a free
text field checked during review.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import yaml  # noqa: E402

from listkit import core  # noqa: E402

HEADER = "# GENERATED by `make sync-form` from config.yaml — do not edit the category list by hand.\n"


def build_form(cfg: dict) -> str:
    form = {
        "name": "Recommend a resource",
        "description": "Suggest a tool, firm, indicator, or reference for the Quint list.",
        "title": "[Resource]: ",
        "labels": ["resource-submission", "validation-pending"],
        "body": [
            {
                "type": "markdown",
                "attributes": {
                    "value": "Thanks! One resource per issue. Prop-firm links should go to the firm's own site, not an affiliate link."
                },
            },
            {
                "type": "input",
                "id": "display_name",
                "attributes": {"label": "Display Name"},
                "validations": {"required": True},
            },
            {
                "type": "dropdown",
                "id": "category",
                "attributes": {
                    "label": "Category",
                    "options": [c["name"] for c in cfg["categories"]],
                },
                "validations": {"required": True},
            },
            {
                "type": "input",
                "id": "subcategory",
                "attributes": {"label": "Sub-Category", "description": "Optional."},
            },
            {
                "type": "input",
                "id": "link",
                "attributes": {"label": "Link", "placeholder": "https://"},
                "validations": {"required": True},
            },
            {"type": "input", "id": "author_name", "attributes": {"label": "Author Name"}},
            {
                "type": "input",
                "id": "author_link",
                "attributes": {"label": "Author Link", "placeholder": "https://"},
            },
            {
                "type": "textarea",
                "id": "description",
                "attributes": {
                    "label": "Description",
                    "description": "One or two factual sentences. No performance claims.",
                },
                "validations": {"required": True},
            },
        ],
    }
    return HEADER + yaml.safe_dump(form, sort_keys=False, allow_unicode=True, width=100)


def sync(cfg: dict | None = None) -> bool:
    out = build_form(cfg or core.load_config())
    path = core.ISSUE_FORM_PATH
    if path.exists() and path.read_text(encoding="utf-8") == out:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(out, encoding="utf-8")
    return True


def main() -> None:
    print("wrote " + str(core.ISSUE_FORM_PATH.relative_to(core.ROOT)) if sync() else "issue form is up to date")


if __name__ == "__main__":
    core.run_cli(main)
